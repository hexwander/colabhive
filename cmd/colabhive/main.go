const maxStdioBridgeBytes = 64 << 20 // 64 MiB max JSON-RPC line / HTTP bridge response

var (
	version   = "1.0.0"
	commit    = "dev"
	buildDate = "unknown"
)

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	code := runMain(ctx, filepath.Base(os.Args[0]), os.Args[1:], os.Stdin, os.Stdout, os.Stderr)
	os.Exit(code)
}

func runMain(
	ctx context.Context,
	invokedAs string,
	args []string,
	in io.Reader,
	out io.Writer,
	errOut io.Writer,
) int {
	ver := server.VersionInfo{
		Version:   version,
		Commit:    commit,
		BuildDate: buildDate,
	}

	// If invoked via `colab` symlink/binary, act as drop-in `colab` CLI.
	baseLower := strings.TrimSuffix(strings.ToLower(invokedAs), ".exe")
	if baseLower == "colab" {
		return server.RunDaemonCLI(ctx, "colab", args, in, out, errOut, ver)
	}

	if len(args) > 0 {
		switch args[0] {
		case "serve", "up":
			return runServe(ctx, args[1:], errOut)
		case "mcp":
			return runMCPStdio(ctx, args[1:], in, out, errOut)
		}
	}

	return server.RunDaemonCLI(ctx, "colabhive", args, in, out, errOut, ver)
}

type serveOptions struct {
	Mode                   string
	TrustProxy             bool
	AutoAdminToken         bool
	AllowLAN               bool
	Host                   string
	Port                   int
	DataDir                string
	DBPath                 string
	WebDir                 string
	Demo                   bool
	MasterKey              string
	AutoGeneratedMasterKey bool
	AdminToken             string
	PublicURL              string
	DefaultStrategy        string
	KeepaliveSec           int
}

func generateRandomAdminToken() (string, error) {
	buf := make([]byte, 24)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return "ch_adm_" + hex.EncodeToString(buf), nil
}

func isStrictLoopbackBindHost(rawHost string) bool {
	h := strings.Trim(strings.TrimSpace(rawHost), "[]")
	if h == "" {
		return false
	}
	if strings.EqualFold(h, "localhost") {
		return true
	}
	if ip := net.ParseIP(h); ip != nil && ip.IsLoopback() {
		return true
	}
	return false
}

func resolveDisplayBaseURL(opts serveOptions, actualPort int) string {
	if strings.TrimSpace(opts.PublicURL) != "" {
		return strings.TrimRight(strings.TrimSpace(opts.PublicURL), "/")
	}
	port := actualPort
	if port <= 0 {
		port = opts.Port
	}
	if port <= 0 {
		port = 7860
	}
	displayHost := strings.TrimSpace(opts.Host)
	if displayHost == "0.0.0.0" || displayHost == "::" || displayHost == "" {
		displayHost = "localhost"
	}
	return fmt.Sprintf("http://%s:%d", displayHost, port)
}

func parseServeOptions(args []string, errOut io.Writer) (serveOptions, error) {
	fs := flag.NewFlagSet("colabhive serve", flag.ContinueOnError)
	fs.SetOutput(errOut)

	defaultMode := envStr("COLABHIVE_MODE", "local")
	defaultTrustProxy := strings.EqualFold(envStr("COLABHIVE_TRUST_PROXY", ""), "true") || envStr("COLABHIVE_TRUST_PROXY", "") == "1"
	defaultAutoToken := strings.EqualFold(envStr("COLABHIVE_AUTO_ADMIN_TOKEN", ""), "true") || envStr("COLABHIVE_AUTO_ADMIN_TOKEN", "") == "1"
	defaultAllowLAN := strings.EqualFold(envStr("COLABHIVE_ALLOW_LAN", ""), "true") || envStr("COLABHIVE_ALLOW_LAN", "") == "1"
	defaultPort := envInt("COLABHIVE_PORT", 7860)
	defaultDataDir := envStr("COLABHIVE_DATA_DIR", "./data")
	defaultDB := envStr("COLABHIVE_DB_PATH", "")
	defaultWebDir := envStr("COLABHIVE_WEB_DIR", "")
	defaultDemo := strings.EqualFold(envStr("COLABHIVE_DEMO", ""), "true") || envStr("COLABHIVE_DEMO", "") == "1"

	var opts serveOptions
	fs.StringVar(&opts.Mode, "mode", defaultMode, "Deployment mode: local (default) or cloud (hardened remote server)")
	fs.BoolVar(&opts.TrustProxy, "trust-proxy", defaultTrustProxy, "Trust X-Forwarded-Proto, X-Forwarded-Host, and X-Forwarded-For reverse-proxy headers")
	fs.BoolVar(&opts.AutoAdminToken, "auto-admin-token", defaultAutoToken, "Auto-generate a random admin token if --admin-token / COLABHIVE_ADMIN_TOKEN is unset")
	fs.BoolVar(&opts.AllowLAN, "allow-lan", defaultAllowLAN, "Allow unauthenticated non-loopback bind in --mode local")
	fs.StringVar(&opts.Host, "host", envStr("COLABHIVE_HOST", ""), "Bind host address (defaults to 127.0.0.1 in local mode, 0.0.0.0 in cloud mode)")
	fs.IntVar(&opts.Port, "port", defaultPort, "HTTP/WS/MCP listen port")
	fs.StringVar(&opts.DataDir, "data-dir", defaultDataDir, "Directory for SQLite vault and plot artifacts")
	fs.StringVar(&opts.DBPath, "db", defaultDB, "SQLite database path (defaults to <data-dir>/colabhive.db)")
	fs.StringVar(&opts.WebDir, "web-dir", defaultWebDir, "Frontend SPA dist directory (auto-detects ./web/dist)")
	fs.BoolVar(&opts.Demo, "demo", defaultDemo, "Launch interactive Demo Cluster with 4 pooled accounts & live 4x G4 experiment")
	fs.StringVar(&opts.MasterKey, "master-key", envStr("COLABHIVE_MASTER_KEY", ""), "AES-256-GCM master secret for OAuth vault")
	fs.StringVar(&opts.AdminToken, "admin-token", envStr("COLABHIVE_ADMIN_TOKEN", ""), "Optional admin Bearer token for /api/v1/* (required in --mode cloud)")
	fs.StringVar(&opts.PublicURL, "public-url", envStr("COLABHIVE_PUBLIC_URL", ""), "External base URL for shareable /contribute/:code links and remote MCP")
	fs.StringVar(&opts.DefaultStrategy, "strategy", envStr("COLABHIVE_DEFAULT_STRATEGY", "waste-zero"), "Default pool routing strategy")
	fs.IntVar(&opts.KeepaliveSec, "keepalive-sec", envInt("COLABHIVE_KEEPALIVE_INTERVAL_SEC", 8), "Keepalive & anti-zombie loop cadence in seconds")

	if err := fs.Parse(args); err != nil {
		return opts, err
	}

	explicitDataDir := strings.TrimSpace(os.Getenv("COLABHIVE_DATA_DIR")) != ""
	fs.Visit(func(f *flag.Flag) {
		if f.Name == "data-dir" {
			explicitDataDir = true
		}
	})

	opts.Mode = strings.ToLower(strings.TrimSpace(opts.Mode))
	if opts.Mode == "" {
		opts.Mode = "local"
	}
	if opts.Mode != "local" && opts.Mode != "cloud" {
		_, _ = fmt.Fprintf(errOut, "[colabhive] invalid --mode %q (expected 'local' or 'cloud')\n", opts.Mode)
		return opts, fmt.Errorf("invalid mode %q", opts.Mode)
	}

	// Default `--host` to `127.0.0.1` in `local` mode when `COLABHIVE_HOST` is unset (and `0.0.0.0` in `cloud` mode)!
	opts.Host = strings.TrimSpace(opts.Host)
	if opts.Host == "" {
		if opts.Mode == "cloud" {
			opts.Host = "0.0.0.0"
		} else {
			opts.Host = "127.0.0.1"
		}
	}
	opts.PublicURL = strings.TrimRight(strings.TrimSpace(opts.PublicURL), "/")

	if opts.DBPath == "" {
		if opts.Demo {
			opts.DBPath = ":memory:"
		} else {
			_ = os.MkdirAll(opts.DataDir, 0o700)
			prodCandidate := filepath.Join(opts.DataDir, "colabhive_prod.db")
			stdCandidate := filepath.Join(opts.DataDir, "colabhive.db")
			if info, pErr := os.Stat(prodCandidate); pErr == nil && !info.IsDir() {
				if _, sErr := os.Stat(stdCandidate); os.IsNotExist(sErr) {
					opts.DBPath = prodCandidate
				} else {
					opts.DBPath = stdCandidate
				}
			} else {
				opts.DBPath = stdCandidate
			}
		}
	} else if opts.DBPath != ":memory:" {
		dbDir := filepath.Dir(opts.DBPath)
		_ = os.MkdirAll(dbDir, 0o700)
		if !explicitDataDir {
			opts.DataDir = dbDir
		}
	}

	if opts.WebDir == "" {
		for _, cand := range []string{"./web/dist", "/app/web/dist"} {
			if info, err := os.Stat(filepath.Join(cand, "index.html")); err == nil && !info.IsDir() {
				opts.WebDir = cand
				break
			}
		}
	}

	return opts, nil
}

func runServe(ctx context.Context, args []string, errOut io.Writer) int {
	opts, err := parseServeOptions(args, errOut)
	if err != nil {
		return 2
	}

	autoMintedAdmin := false
	if opts.AutoAdminToken && strings.TrimSpace(opts.AdminToken) == "" {
		tok, genErr := generateRandomAdminToken()
		if genErr != nil {
			_, _ = fmt.Fprintf(errOut, "[colabhive] Failed to generate random admin token: %v\n", genErr)
			return 1
		}
		opts.AdminToken = tok
		autoMintedAdmin = true
	}

	// If `--mode local` binds a non-loopback address (`0.0.0.0`, LAN IP) without `AdminToken`,
	// `--demo`, or `--allow-lan`, auto-generate a session `AdminToken` so LAN peers never get open vault access!
	if opts.Mode == "local" && !isStrictLoopbackBindHost(opts.Host) &&
		strings.TrimSpace(opts.AdminToken) == "" && !opts.Demo && !opts.AllowLAN {
		tok, genErr := generateRandomAdminToken()
		if genErr != nil {
			_, _ = fmt.Fprintf(errOut, "[colabhive] Failed to generate random admin token for non-loopback bind: %v\n", genErr)
			return 1
		}
		opts.AdminToken = tok
		autoMintedAdmin = true
	}

	if opts.Mode == "cloud" && strings.TrimSpace(opts.AdminToken) == "" && !opts.Demo {
		_, _ = fmt.Fprintln(errOut, "[colabhive] --mode cloud requires --admin-token or COLABHIVE_ADMIN_TOKEN (or pass --auto-admin-token)")
		return 2
	}

	if opts.Mode == "cloud" && strings.TrimSpace(opts.MasterKey) == "" && !opts.Demo {
		if opts.AutoAdminToken {
			mk, mkErr := vault.LoadOrCreateMasterKeyForDB(opts.DBPath, opts.DataDir)
			if mkErr != nil {
				_, _ = fmt.Fprintf(errOut, "[colabhive] Failed to persist master key: %v\n", mkErr)
				return 1
			}
			opts.MasterKey = mk
			opts.AutoGeneratedMasterKey = true
		} else {
			_, _ = fmt.Fprintln(errOut, "[colabhive] --mode cloud requires --master-key or COLABHIVE_MASTER_KEY (or pass --auto-admin-token)")
			return 2
		}
	}

	stack, cleanup, err := buildControlPlaneStack(ctx, opts)
	if err != nil {
		_, _ = fmt.Fprintf(errOut, "[colabhive] Startup failed: %v\n", err)
		return 1
	}
	defer cleanup()

	addr := net.JoinHostPort(opts.Host, strconv.Itoa(opts.Port))
	ln, err := net.Listen("tcp", addr)
	if err != nil {
		_, _ = fmt.Fprintf(errOut, "[colabhive] Failed to bind %s: %v\n", addr, err)
		return 1
	}

	// Persist `~/.colabhive/daemon.json` in local mode so `colabhive mcp` (`stdio`), CLI, and Desktop Tray
	// always discover the exact live loopback port and production SQLite path.
	actualPort := opts.Port
	if tcpAddr, ok := ln.Addr().(*net.TCPAddr); ok && tcpAddr.Port > 0 {
		actualPort = tcpAddr.Port
	}
	if opts.Mode != "cloud" {
		loopbackHost := opts.Host
		if loopbackHost == "" || loopbackHost == "0.0.0.0" || loopbackHost == "::" {
			loopbackHost = "127.0.0.1"
		}
		daemonURL := fmt.Sprintf("http://%s", net.JoinHostPort(loopbackHost, strconv.Itoa(actualPort)))
		_ = server.WriteDaemonInfo(server.DaemonInfo{
			URL:       daemonURL,
			PID:       os.Getpid(),
			DBPath:    opts.DBPath,
			StartedAt: time.Now().UTC(),
		})
	}

	httpSrv := &http.Server{
		Handler:           stack.Handler(),
		ReadHeaderTimeout: 15 * time.Second,
	}

	bannerURL := resolveDisplayBaseURL(opts, actualPort)
	modeLabel := "LOCAL (Desktop / Workstation)"
	if opts.Mode == "cloud" {
		modeLabel = "CLOUD (Hardened Remote Server)"
		if opts.TrustProxy {
			modeLabel += " · TrustProxy=ON"
		}
	}
	authLabel := "NO (Localhost Loopback Access)"
	if opts.Mode == "cloud" || strings.TrimSpace(opts.AdminToken) != "" {
		authLabel = "YES (Admin Bearer Token + Scoped ch_sk_... Agent Keys)"
	}

	demoBadge := ""
	if opts.Demo {
		demoBadge = " [DEMO CLUSTER SEEDED: 4 Accounts · 4× G4 Shards]"
	}
	_, _ = fmt.Fprintf(errOut,
		"🐝 ColabHive v%s listening on %s%s\n"+
			"   • Mode              : %s\n"+
			"   • Auth Required     : %s\n"+
			"   • Web Observatory   : %s\n"+
			"   • MCP Endpoint      : %s/mcp\n"+
			"   • Contribute Portal : %s/contribute/<invite_code>\n"+
			"   • SQLite Vault      : %s\n",
		version, ln.Addr().String(), demoBadge,
		modeLabel, authLabel,
		bannerURL, bannerURL, bannerURL, opts.DBPath,
	)
	if autoMintedAdmin {
		_, _ = fmt.Fprintf(errOut,
			"   • Auto Admin Token  : %s  (save this token for Console sign-in!)\n",
			opts.AdminToken,
		)
	}

	errCh := make(chan error, 1)
	go func() {
		if sErr := httpSrv.Serve(ln); sErr != nil && sErr != http.ErrServerClosed {
			errCh <- sErr
		} else {
			errCh <- nil
		}
	}()

	select {
	case <-ctx.Done():
		shutCtx, cancel := context.WithTimeout(context.Background(), 8*time.Second)
		defer cancel()
		_ = httpSrv.Shutdown(shutCtx)
		return 0
	case sErr := <-errCh:
		if sErr != nil {
			_, _ = fmt.Fprintf(errOut, "[colabhive] HTTP server error: %v\n", sErr)
			return 1
		}
		return 0
	}
}

func wirePoolSessionDrainer(poolSvc any, rtEngine any) {
	type sessionDrainerTarget interface {
		SetSessionDrainer(func(context.Context, string) error)
	}
	type accountSessionStopper interface {
		StopManagedSessionsForAccount(context.Context, string) error
	}
	if dt, ok := poolSvc.(sessionDrainerTarget); ok {
		if stopper, okS := rtEngine.(accountSessionStopper); okS {
			dt.SetSessionDrainer(stopper.StopManagedSessionsForAccount)
		}
	}
}

func buildControlPlaneStack(ctx context.Context, opts serveOptions) (*server.Server, func(), error) {
	explicitMasterKey := strings.TrimSpace(opts.MasterKey) != "" && !opts.AutoGeneratedMasterKey
	if strings.TrimSpace(opts.MasterKey) == "" && opts.DBPath != "" && opts.DBPath != ":memory:" {
		mk, mkErr := vault.LoadOrCreateMasterKeyForDB(opts.DBPath, opts.DataDir)
		if mkErr != nil {
			return nil, nil, fmt.Errorf("failed to initialize master key file for %s: %w", opts.DBPath, mkErr)
		}
		opts.MasterKey = mk
		opts.AutoGeneratedMasterKey = true
	}

	st, err := store.OpenSQLite(opts.DBPath)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to open SQLite store (%s): %w", opts.DBPath, err)
	}

	hub := events.NewHub()
	txFactory := proxy.NewTransportFactory()

	var mockSrv *mockcolab.Server
	var poolCfg pool.Config
	tunnelURL := models.ColabTunnelDomain
	publicAPIURL := models.ColabPublicAPIDomain

	seedBaseURL := resolveDisplayBaseURL(opts, opts.Port)
	strictCloudVault := strings.EqualFold(strings.TrimSpace(opts.Mode), "cloud") && explicitMasterKey
	if opts.Demo {
		mockSrv = mockcolab.NewServer()
		poolCfg = mockSrv.PoolConfig(opts.MasterKey)
		poolCfg.StrictVaultKey = strictCloudVault
		poolCfg.PublicBaseURL = seedBaseURL
		tunnelURL = mockSrv.URL
		publicAPIURL = mockSrv.URL
	} else {
		poolCfg = pool.Config{
			MasterSecret:            opts.MasterKey,
			StrictVaultKey:          strictCloudVault,
			PublicBaseURL:           opts.PublicURL,
			CustomOAuthClientID:     envStr("COLABHIVE_OAUTH_CLIENT_ID", ""),
			CustomOAuthClientSecret: envStr("COLABHIVE_OAUTH_CLIENT_SECRET", ""),
		}
	}

	poolSvc := pool.NewService(st, hub, poolCfg)
	rtr := router.NewService(st, poolSvc, hub)

	if opts.DefaultStrategy != "" {
		if pol, pErr := rtr.GetPolicy(ctx); pErr == nil && pol != nil {
			pol.DefaultStrategy = router.NormalizeStrategy(models.RoutingStrategy(opts.DefaultStrategy), models.StrategyWasteZero)
			_, _ = rtr.UpdatePolicy(ctx, *pol)
		}
	}

	artifactsDir := filepath.Join(opts.DataDir, "artifacts")
	if opts.DBPath == ":memory:" {
		artifactsDir = filepath.Join(os.TempDir(), "colabhive-demo-artifacts")
	}

	keepDur := time.Duration(opts.KeepaliveSec) * time.Second
	if keepDur <= 0 {
		keepDur = 8 * time.Second
	}

	rtEngine := runtime.NewConcreteEngine(st, poolSvc, rtr, hub, runtime.Options{
		DemoMode:             false, // When opts.Demo is true, mockSrv handles real /tun/m + Jupyter WS frames!
		TunnelBaseURL:        tunnelURL,
		PublicAPIBaseURL:     publicAPIURL,
		KeepaliveInterval:    keepDur,
		ResourcePollInterval: 10 * time.Second,
		ArtifactsDir:         artifactsDir,
		HTTPClientFactory: func(proxyURL string) (*http.Client, *websocket.Dialer, error) {
			hc, hErr := txFactory.HTTPClient(proxyURL, 15*time.Minute)
			if hErr != nil {
				return nil, nil, hErr
			}
			wd, wErr := txFactory.WebSocketDialer(proxyURL, 20*time.Second)
			if wErr != nil {
				return nil, nil, wErr
			}
			return hc, wd, nil
		},
	})
	wirePoolSessionDrainer(poolSvc, rtEngine)

	if opts.Demo {
		_, _ = mockcolab.SeedDemoCluster(ctx, st, poolSvc, mockSrv)
		_ = server.SeedDemoCluster(ctx, st, rtr, artifactsDir, seedBaseURL)
	} else {
		// Immediately discover and adopt any live external Colab tasks running on pooled accounts.
		rtEngine.TriggerSyncAsync()
	}

	mcpSrv := mcp.NewServer(poolSvc, rtEngine, rtr, hub)
	if opts.AdminToken != "" {
		mcpSrv.SetAdminToken(opts.AdminToken)
	}
	mcpSrv.SetCloudMode(strings.EqualFold(opts.Mode, "cloud"))

	srv := server.New(st, poolSvc, rtEngine, rtr, hub, mcpSrv, server.Config{
		Version:              version,
		Mode:                 opts.Mode,
		TrustProxy:           opts.TrustProxy,
		AdminToken:           opts.AdminToken,
		WebDir:               opts.WebDir,
		ArtifactsDir:         artifactsDir,
		PublicURL:            opts.PublicURL,
		DemoMode:             opts.Demo,
		KeepaliveIntervalSec: opts.KeepaliveSec,
		ResourcePollSec:      10,
	})

	cleanup := func() {
		_ = rtEngine.Close()
		if mockSrv != nil {
			mockSrv.Close()
		}
		_ = st.Close()
	}
	return srv, cleanup, nil
}

// ============================================================================
// Dual-Mode `colabhive mcp [stdio]` (Daemon Bridge OR Embedded Serverless)
// ============================================================================

func runMCPStdio(ctx context.Context, args []string, in io.Reader, out io.Writer, errOut io.Writer) int {
	// Strip optional positional `"stdio"` sub-arg (`colabhive mcp stdio ...` & `colabhive mcp ...` both work!)
	filtered := make([]string, 0, len(args))
	for _, a := range args {
		if a == "stdio" {
			continue
		}
		filtered = append(filtered, a)
	}

	fs := flag.NewFlagSet("colabhive mcp", flag.ContinueOnError)
	fs.SetOutput(errOut)
	var serverURL, apiKey, dbPath, strategy, account string
	var demo, embeddedOnly bool
	fs.StringVar(&serverURL, "server", envStr("COLABHIVE_URL", ""), "Running ColabHive daemon URL")
	fs.StringVar(&apiKey, "api-key", envStr("COLABHIVE_API_KEY", ""), "ColabHive ch_sk_... API key")
	fs.StringVar(&dbPath, "db", envStr("COLABHIVE_DB_PATH", ""), "SQLite database path when running standalone")
	fs.StringVar(&strategy, "strategy", envStr("COLABHIVE_DEFAULT_STRATEGY", ""), "Default routing strategy")
	fs.StringVar(&account, "account", "", "Optional pinned account selector")
	fs.BoolVar(&demo, "demo", strings.EqualFold(envStr("COLABHIVE_DEMO", ""), "true"), "Enable embedded demo pool")
	fs.BoolVar(&embeddedOnly, "embedded", false, "Force standalone embedded mode without probing local daemon")
	if err := fs.Parse(filtered); err != nil {
		return 2
	}

	explicitKey := strings.TrimSpace(apiKey)
	if explicitKey == "" {
		explicitKey = strings.TrimSpace(os.Getenv("COLABHIVE_API_KEY"))
	}
	bridgeKey := explicitKey
	if bridgeKey == "" {
		bridgeKey = strings.TrimSpace(os.Getenv("COLABHIVE_ADMIN_TOKEN"))
	}

	daemonInfo, _ := server.ReadDaemonInfo()
	explicitServer := strings.TrimRight(strings.TrimSpace(serverURL), "/")

	// If an explicit `--server` / `COLABHIVE_URL` was supplied and is unreachable, fail fast
	// rather than silently opening an unrelated local SQLite DB!
	if !embeddedOnly && explicitServer != "" {
		liveDaemon := discoverHealthyDaemonURL(ctx, explicitServer, daemonInfo)
		if liveDaemon == "" {
			_, _ = fmt.Fprintf(errOut, "[colabhive mcp] cannot reach explicit ColabHive server at %s\n", explicitServer)
			return 1
		}
		if err := bridgeStdioToHTTPMCP(ctx, liveDaemon+"/mcp", bridgeKey, strategy, account, in, out); err != nil && err != context.Canceled {
			_, _ = fmt.Fprintf(errOut, "[colabhive mcp] bridge error: %v\n", err)
			return 1
		}
		return 0
	}

	// Probe running daemon first (unless `--embedded` or explicit `--db` / `--demo`).
	if !embeddedOnly && strings.TrimSpace(dbPath) == "" && !demo {
		if liveDaemon := discoverHealthyDaemonURL(ctx, "", daemonInfo); liveDaemon != "" {
			if err := bridgeStdioToHTTPMCP(ctx, liveDaemon+"/mcp", bridgeKey, strategy, account, in, out); err != nil && err != context.Canceled {
				_, _ = fmt.Fprintf(errOut, "[colabhive mcp] bridge error: %v\n", err)
				return 1
			}
			return 0
		}
	}

	// Fallback: Standalone in-process embedded MCP server using `~/.colabhive/daemon.json`'s `db_path`
	// (so `colabhive mcp` NEVER split-brains onto an empty `./data/colabhive.db` relative to IDE CWD!).
	resolvedDB := resolveEmbeddedMCPDBPath(dbPath, demo, daemonInfo)

	masterSecret := envStr("COLABHIVE_MASTER_KEY", "")
	if masterSecret == "" && !demo && resolvedDB != "" && resolvedDB != ":memory:" {
		mk, mkErr := vault.LoadOrCreateMasterKeyForDB(resolvedDB, envStr("COLABHIVE_DATA_DIR", ""))
		if mkErr != nil {
			_, _ = fmt.Fprintf(errOut, "[colabhive mcp] failed to initialize master key for %s: %v\n", resolvedDB, mkErr)
			return 1
		}
		masterSecret = mk
	}

	st, err := store.OpenSQLite(resolvedDB)
	if err != nil {
		_, _ = fmt.Fprintf(errOut, "[colabhive mcp] failed to open SQLite (%s): %v\n", resolvedDB, err)
		return 1
	}
	defer st.Close()

	hub := events.NewHub()
	txFactory := proxy.NewTransportFactory()

	var mockSrv *mockcolab.Server
	var poolCfg pool.Config
	tunnelURL := models.ColabTunnelDomain
	if demo {
		mockSrv = mockcolab.NewServer()
		defer mockSrv.Close()
		poolCfg = mockSrv.PoolConfig(masterSecret)
		tunnelURL = mockSrv.URL
	} else {
		poolCfg = pool.Config{MasterSecret: masterSecret}
	}

	poolSvc := pool.NewService(st, hub, poolCfg)
	rtr := router.NewService(st, poolSvc, hub)
	rtEngine := runtime.NewConcreteEngine(st, poolSvc, rtr, hub, runtime.Options{
		TunnelBaseURL: tunnelURL,
		ArtifactsDir:  filepath.Join(os.TempDir(), "colabhive-mcp-artifacts"),
		HTTPClientFactory: func(proxyURL string) (*http.Client, *websocket.Dialer, error) {
			hc, hErr := txFactory.HTTPClient(proxyURL, 15*time.Minute)
			if hErr != nil {
				return nil, nil, hErr
			}
			wd, wErr := txFactory.WebSocketDialer(proxyURL, 20*time.Second)
			if wErr != nil {
				return nil, nil, wErr
			}
			return hc, wd, nil
		},
	})
	defer rtEngine.Close()
	wirePoolSessionDrainer(poolSvc, rtEngine)

	if demo {
		_, _ = mockcolab.SeedDemoCluster(ctx, st, poolSvc, mockSrv)
	}

	effectiveStrat := strategy
	if strings.TrimSpace(effectiveStrat) == "" {
		effectiveStrat = "waste-zero"
	}
	mcpSrv := mcp.NewServer(poolSvc, rtEngine, rtr, hub)
	mcpSrv.SetStdioDefaults(models.RoutingStrategy(effectiveStrat), account)
	if explicitKey != "" {
		mcpSrv.SetStdioAPIKey(explicitKey)
	}
	if adminTok := strings.TrimSpace(os.Getenv("COLABHIVE_ADMIN_TOKEN")); adminTok != "" {
		mcpSrv.SetAdminToken(adminTok)
	}

	if err := mcpSrv.ServeStdio(ctx, in, out); err != nil && err != context.Canceled {
		_, _ = fmt.Fprintf(errOut, "[colabhive mcp] stdio error: %v\n", err)
		return 1
	}
	return 0
}

func discoverHealthyDaemonURL(ctx context.Context, explicitURL string, info *server.DaemonInfo) string {
	fallbackLoopback := strings.TrimSpace(os.Getenv("COLABHIVE_FALLBACK_DAEMON_URL"))
	if fallbackLoopback == "" && strings.TrimSpace(os.Getenv("COLABHIVE_DAEMON_INFO_PATH")) == "" {
		fallbackLoopback = "http://127.0.0.1:7860"
	}
	return discoverHealthyDaemonURLWithFallback(ctx, explicitURL, info, fallbackLoopback)
}

func discoverHealthyDaemonURLWithFallback(
	ctx context.Context,
	explicitURL string,
	info *server.DaemonInfo,
	fallbackLoopbackURL string,
) string {
	explicit := strings.TrimRight(strings.TrimSpace(explicitURL), "/")
	if explicit != "" {
		if isDaemonHealthy(ctx, explicit) {
			return explicit
		}
		return ""
	}

	fb := strings.TrimRight(strings.TrimSpace(fallbackLoopbackURL), "/")

	if info != nil && info.URL != "" {
		cand := strings.TrimRight(info.URL, "/")
		if isDaemonHealthy(ctx, cand) {
			return cand
		}
		if fresh, err := server.ReadDaemonInfo(); err == nil && fresh != nil && fresh.URL != "" {
			freshURL := strings.TrimRight(fresh.URL, "/")
			if !strings.EqualFold(freshURL, cand) && isDaemonHealthy(ctx, freshURL) {
				return freshURL
			}
		}
		// If `daemon.json` holds a stale unreachable ephemeral port, also probe `:7860` before embedded fallback!
		if fb != "" && !strings.EqualFold(fb, cand) && isDaemonHealthy(ctx, fb) {
			return fb
		}
		return ""
	}

	if fb != "" && isDaemonHealthy(ctx, fb) {
		return fb
	}
	if fresh, err := server.ReadDaemonInfo(); err == nil && fresh != nil && fresh.URL != "" {
		freshURL := strings.TrimRight(fresh.URL, "/")
		if isDaemonHealthy(ctx, freshURL) {
			return freshURL
		}
	}
	return ""
}

func resolveEmbeddedMCPDBPath(explicitDB string, demo bool, info *server.DaemonInfo) string {
	if strings.TrimSpace(explicitDB) != "" {
		return strings.TrimSpace(explicitDB)
	}
	if demo {
		return ":memory:"
	}
	if info != nil && info.DBPath != "" && info.DBPath != ":memory:" {
		return info.DBPath
	}

	// Check sibling `../data/colabhive_prod.db` or `../data/colabhive.db` relative to binary location.
	if exePath, err := os.Executable(); err == nil && exePath != "" {
		binDir := filepath.Dir(exePath)
		for _, rel := range []string{
			filepath.Join(binDir, "..", "data", "colabhive_prod.db"),
			filepath.Join(binDir, "..", "data", "colabhive.db"),
			filepath.Join(binDir, "data", "colabhive_prod.db"),
			filepath.Join(binDir, "data", "colabhive.db"),
		} {
			if fi, sErr := os.Stat(rel); sErr == nil && !fi.IsDir() {
				if abs, aErr := filepath.Abs(rel); aErr == nil {
					return abs
				}
				return rel
			}
		}
	}

	if customDataDir := strings.TrimSpace(os.Getenv("COLABHIVE_DATA_DIR")); customDataDir != "" {
		_ = os.MkdirAll(customDataDir, 0o700)
		prodCand := filepath.Join(customDataDir, "colabhive_prod.db")
		if fi, sErr := os.Stat(prodCand); sErr == nil && !fi.IsDir() {
			return prodCand
		}
		return filepath.Join(customDataDir, "colabhive.db")
	}

	for _, localCand := range []string{
		filepath.Join("./data", "colabhive_prod.db"),
		filepath.Join("./data", "colabhive.db"),
	} {
		if fi, sErr := os.Stat(localCand); sErr == nil && !fi.IsDir() {
			return localCand
		}
	}

	// Safe user-home fallback so read-only GUI working directories (e.g. Program Files / System32) never fail.
	if home, hErr := os.UserHomeDir(); hErr == nil && home != "" {
		homeData := filepath.Join(home, ".colabhive", "data")
		if mkErr := os.MkdirAll(homeData, 0o700); mkErr == nil {
			return filepath.Join(homeData, "colabhive.db")
		}
	}
	_ = os.MkdirAll("./data", 0o700)
	return filepath.Join("./data", "colabhive.db")
}

func isDaemonHealthy(ctx context.Context, baseURL string) bool {
	probeCtx, cancel := context.WithTimeout(ctx, 2500*time.Millisecond)
	defer cancel()
	req, err := http.NewRequestWithContext(probeCtx, http.MethodGet, baseURL+"/api/v1/health?fast=1", nil)
	if err != nil {
		return false
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return false
	}
	_, _ = io.Copy(io.Discard, resp.Body)
	_ = resp.Body.Close()
	return resp.StatusCode == http.StatusOK
}

func isInitializeRequestLine(raw []byte) bool {
	if len(raw) == 0 || raw[0] == '[' {
		return false
	}
	var peek struct {
		Method string `json:"method"`
	}
	if err := json.Unmarshal(raw, &peek); err != nil {
		return false
	}
	return strings.TrimSpace(peek.Method) == "initialize"
}

func extractJSONRPCErrorTarget(raw []byte) (id json.RawMessage, shouldReply bool) {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 {
		return nil, false
	}
	if trimmed[0] == '[' {
		var batch []struct {
			ID     json.RawMessage `json:"id"`
			Method string          `json:"method"`
		}
		if err := json.Unmarshal(trimmed, &batch); err != nil || len(batch) == 0 {
			return json.RawMessage("null"), true
		}
		for _, item := range batch {
			tid := bytes.TrimSpace(item.ID)
			m := strings.TrimSpace(item.Method)
			if len(tid) > 0 && !bytes.Equal(tid, []byte("null")) && m != "" && !strings.HasPrefix(m, "notifications/") {
				return tid, true
			}
		}
		return nil, false
	}

	var single struct {
		ID     json.RawMessage `json:"id"`
		Method string          `json:"method"`
	}
	if err := json.Unmarshal(trimmed, &single); err != nil {
		return json.RawMessage("null"), true
	}
	tid := bytes.TrimSpace(single.ID)
	m := strings.TrimSpace(single.Method)
	if len(tid) == 0 || bytes.Equal(tid, []byte("null")) || m == "" || strings.HasPrefix(m, "notifications/") {
		return nil, false
	}
	return tid, true
}

func isValidJSONRPCEnvelope(raw []byte) bool {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 {
		return false
	}
	if trimmed[0] == '[' {
		var arr []map[string]any
		return json.Unmarshal(trimmed, &arr) == nil && len(arr) > 0
	}
	var obj map[string]any
	if err := json.Unmarshal(trimmed, &obj); err != nil {
		return false
	}
	v, _ := obj["jsonrpc"].(string)
	return v == "2.0"
}

func buildJSONRPCBridgeError(id json.RawMessage, code int, msg string) []byte {
	if len(id) == 0 {
		id = json.RawMessage("null")
	}
	payload := map[string]any{
		"jsonrpc": "2.0",
		"id":      id,
		"error": map[string]any{
			"code":    code,
			"message": msg,
		},
	}
	b, _ := json.Marshal(payload)
	return b
}

func readBridgeJSONRPCLine(r *bufio.Reader, maxBytes int) (line []byte, tooLong bool, err error) {
	var accum []byte
	exceeded := false
	for {
		frag, rErr := r.ReadSlice('\n')
		if !exceeded {
			if len(accum)+len(frag) > maxBytes {
				exceeded = true
				accum = nil
			} else if rErr == nil && len(accum) == 0 {
				return frag, false, nil
			} else {
				accum = append(accum, frag...)
			}
		}
		if rErr == nil {
			if exceeded {
				return nil, true, nil
			}
			return accum, false, nil
		}
		if errors.Is(rErr, bufio.ErrBufferFull) {
			continue
		}
		if errors.Is(rErr, io.EOF) {
			if exceeded {
				return nil, true, nil
			}
			if len(accum) > 0 {
				return accum, false, nil
			}
			return nil, false, io.EOF
		}
		return nil, exceeded, rErr
	}
}

func bridgeStdioToHTTPMCP(
	ctx context.Context,
	mcpEndpoint string,
	apiKey string,
	strategy string,
	account string,
	in io.Reader,
	out io.Writer,
) error {
	var sessMu sync.RWMutex
	stickySessionID := "mcp-stdio-bridge-" + strings.ReplaceAll(uuid.NewString(), "-", "")[:12]

	// Timeout: 0 so multi-minute GPU provisioning, `execute_code`, and `colab_install_packages` never abort!
	client := &http.Client{Timeout: 0}
	reader := bufio.NewReaderSize(in, 64*1024)

	var (
		writeMu      sync.Mutex
		wg           sync.WaitGroup
		writeErrOnce sync.Once
		writeErr     error
	)

	writeLine := func(payload []byte) error {
		writeMu.Lock()
		defer writeMu.Unlock()
		buf := make([]byte, len(payload)+1)
		copy(buf, payload)
		buf[len(payload)] = '\n'
		if _, err := out.Write(buf); err != nil {
			writeErrOnce.Do(func() { writeErr = err })
			return err
		}
		return nil
	}

	forwardOne := func(rawLine []byte) error {
		sessMu.RLock()
		curSid := stickySessionID
		sessMu.RUnlock()

		req, err := http.NewRequestWithContext(ctx, http.MethodPost, mcpEndpoint, bytes.NewReader(rawLine))
		if err != nil {
			if reqID, reply := extractJSONRPCErrorTarget(rawLine); reply {
				return writeLine(buildJSONRPCBridgeError(reqID, -32603, "invalid HTTP bridge request: "+err.Error()))
			}
			return nil
		}
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set("Accept", "application/json")
		req.Header.Set("Mcp-Session-Id", curSid)
		if strings.TrimSpace(apiKey) != "" {
			req.Header.Set("Authorization", "Bearer "+strings.TrimSpace(apiKey))
		}
		if strings.TrimSpace(strategy) != "" {
			req.Header.Set("X-ColabHive-Strategy", strings.TrimSpace(strategy))
		}
		if strings.TrimSpace(account) != "" {
			req.Header.Set("X-ColabHive-Account", strings.TrimSpace(account))
		}

		resp, err := client.Do(req)
		if err != nil {
			if ctx.Err() != nil {
				return ctx.Err()
			}
			if reqID, reply := extractJSONRPCErrorTarget(rawLine); reply {
				return writeLine(buildJSONRPCBridgeError(reqID, -32603, "ColabHive daemon transport error: "+err.Error()))
			}
			return nil
		}
		if srvSid := strings.TrimSpace(resp.Header.Get("Mcp-Session-Id")); srvSid != "" {
			sessMu.Lock()
			stickySessionID = srvSid
			sessMu.Unlock()
		}
		rawResp, _ := io.ReadAll(io.LimitReader(resp.Body, maxStdioBridgeBytes+1))
		if len(rawResp) > maxStdioBridgeBytes {
			_, _ = io.Copy(io.Discard, resp.Body)
			_ = resp.Body.Close()
			if reqID, reply := extractJSONRPCErrorTarget(rawLine); reply {
				return writeLine(buildJSONRPCBridgeError(reqID, -32603, "ColabHive MCP response exceeded 64 MiB bridge limit"))
			}
			return nil
		}
		_ = resp.Body.Close()

		if resp.StatusCode == http.StatusAccepted {
			return nil
		}

		trimmedResp := bytes.TrimSpace(rawResp)
		if resp.StatusCode < 200 || resp.StatusCode >= 300 {
			if isValidJSONRPCEnvelope(trimmedResp) {
				return writeLine(trimmedResp)
			}
			if reqID, reply := extractJSONRPCErrorTarget(rawLine); reply {
				errDetail := strings.TrimSpace(string(trimmedResp))
				var parsedErr struct {
					Error   string `json:"error"`
					Message string `json:"message"`
				}
				if json.Unmarshal(trimmedResp, &parsedErr) == nil {
					if parsedErr.Error != "" {
						errDetail = parsedErr.Error
					} else if parsedErr.Message != "" {
						errDetail = parsedErr.Message
					}
				}
				if errDetail == "" {
					errDetail = resp.Status
				}
				return writeLine(buildJSONRPCBridgeError(reqID, -32603, fmt.Sprintf("ColabHive HTTP %d: %s", resp.StatusCode, errDetail)))
			}
			return nil
		}

		if len(trimmedResp) > 0 {
			return writeLine(trimmedResp)
		}
		return nil
	}

	errCh := make(chan error, 1)
	go func() {
		for {
			rawLine, tooLong, rErr := readBridgeJSONRPCLine(reader, maxStdioBridgeBytes)
			if tooLong {
				if wErr := writeLine(buildJSONRPCBridgeError(json.RawMessage("null"), -32600, "JSON-RPC frame exceeds 64 MiB limit")); wErr != nil {
					wg.Wait()
					errCh <- wErr
					return
				}
				continue
			}
			if rErr != nil {
				wg.Wait()
				if errors.Is(rErr, io.EOF) {
					errCh <- writeErr
					return
				}
				errCh <- rErr
				return
			}

			trimmed := bytes.TrimSpace(rawLine)
			if len(trimmed) == 0 {
				continue
			}
			lineCopy := append([]byte(nil), trimmed...)
			// Run `initialize` synchronously so the server-assigned `Mcp-Session-Id` is established first;
			// dispatch all subsequent calls concurrently (`writeMu`-guarded) with zero head-of-line blocking!
			if isInitializeRequestLine(lineCopy) {
				if fErr := forwardOne(lineCopy); fErr != nil && fErr != context.Canceled {
					wg.Wait()
					errCh <- fErr
					return
				}
			} else {
				wg.Add(1)
				go func(payload []byte) {
					defer wg.Done()
					_ = forwardOne(payload)
				}(lineCopy)
			}
		}
	}()

	select {
	case <-ctx.Done():
		return ctx.Err()
	case err := <-errCh:
		return err
	}
}

func envStr(key, def string) string {
	if v := strings.TrimSpace(os.Getenv(key)); v != "" {
		return v
	}
	return def
}

func envInt(key string, def int) int {
	if v := strings.TrimSpace(os.Getenv(key)); v != "" {
		if n, err := strconv.Atoi(v); err == nil {
			return n
		}
	}
	return def
}
